/**
 * Writes `src/app/icon.svg` from `mark-geometry` so favicon paths cannot drift
 * from the React mark. The mark carries its own dark tile, so one set of hexes
 * reads on light and dark tab bars without a `prefers-color-scheme` block.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  markBars,
  markColors,
  markHandle,
  markLens,
  markSpike,
  markTile,
  markViewBox,
} from '../src/components/mongoscope-mark/mark-geometry'

function buildFaviconSvg(): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${markViewBox}" fill="none" stroke-linecap="round" stroke-linejoin="round">
  <!-- Generated by scripts/generate-icon.ts from mark-geometry. Do not edit by hand. -->
  <rect x="${markTile.x}" y="${markTile.y}" width="${markTile.size}" height="${markTile.size}" rx="${markTile.radius}" fill="${markColors.tile}" stroke="${markColors.tileEdge}"/>
  <circle cx="${markLens.cx}" cy="${markLens.cy}" r="${markLens.r}" stroke="${markColors.lens}" stroke-width="${markLens.strokeWidth}"/>
  <path d="${markHandle.d}" stroke="${markColors.lens}" stroke-width="${markHandle.strokeWidth}"/>
  <path d="${markBars.d}" stroke="${markColors.bars}" stroke-width="${markBars.strokeWidth}"/>
  <path d="${markSpike.d}" stroke="${markColors.spike}" stroke-width="${markSpike.strokeWidth}"/>
</svg>
`
}

const docsRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(docsRoot, 'src/app/icon.svg')

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, buildFaviconSvg())
console.log(`wrote ${outPath}`)
